# -*- coding: utf-8 -*-
"""
Enrich a WeChat-article XLSX with article body text and matched products.

The script reads an XLSX generated by wechat_album_export.py, fetches each URL,
extracts text from the WeChat article body, matches products from
yonyou_product_knowledge_base.csv, and writes a new XLSX with two extra columns:
"正文" and "产品".

Usage:
    python enrich_wechat_articles.py
    python enrich_wechat_articles.py --input 数智先锋_文章链接_含发布时间.xlsx
"""

